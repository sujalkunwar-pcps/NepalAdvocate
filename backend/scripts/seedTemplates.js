async function seed() {
  try {
    console.log('Connecting to MongoDB...');
    await mongoose.connect('mongodb://127.0.0.1:27017/nepaladvocate');
    console.log('Connected!');

    // Find any admin or lawyer user to attach as creator
    const creatorUser = await User.findOne({ role: 'ADMIN' }) || await User.findOne({ role: 'LAWYER' });
    if (!creatorUser) {
      console.log('No Admin or Lawyer found to attribute templates. Please run auth seeds first.');
      process.exit(1);
    }

    console.log('Clearing existing templates...');
    await LegalTemplate.deleteMany({});

    console.log('Inserting new legal templates...');
    const createdTemplates = templates.map(t => ({
      ...t,
      createdBy: creatorUser._id,
      isActive: true,
      usageCount: 0
    }));

    await LegalTemplate.insertMany(createdTemplates);
    console.log('Successfully seeded ' + createdTemplates.length + ' templates!');
    
    // Save to backend/data/legal_templates.json
    const fs = require('fs');
    fs.writeFileSync('data/legal_templates.json', JSON.stringify(templates, null, 2), 'utf-8');
    console.log('Saved templates backup to data/legal_templates.json');
    
    process.exit(0);
  } catch (error) {
    console.error('Seeding error:', error);
    process.exit(1);
  }
}

seed();